import os
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import classification_report, confusion_matrix, ConfusionMatrixDisplay

# 1. 載入並檢查真實錄製資料
df = pd.read_csv("traffic_features.csv").dropna()
print("=== 樣本分佈檢查 ===")
print(df["label"].value_counts().rename({0: "Bulk/Media (0)", 1: "Interactive (1)"}))

if df["label"].nunique() < 2:
    raise ValueError("資料集目前只有單一標籤！請確認 label=0 與 label=1 都有成功錄入。")

features = ["rx_pps", "tx_pps", "small_ratio", "avg_size", "iat_var"]
X = df[features].values
y = df["label"].values

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.25, random_state=42, stratify=y
)

# 2. 標準化 + 平衡權重邏輯斯迴歸訓練
scaler = StandardScaler()
X_train_s = scaler.fit_transform(X_train)
X_test_s = scaler.transform(X_test)

clf = LogisticRegression(C=1.0, max_iter=1000, class_weight="balanced")
clf.fit(X_train_s, y_train)
y_pred = clf.predict(X_test_s)

# 3. 印出評估指標（直接用於海報與簡報）
cm = confusion_matrix(y_test, y_pred)
print("\n=== Confusion Matrix ===")
print(cm)
print("\n=== Classification Report ===")
print(classification_report(y_test, y_pred, target_names=["Bulk/Media (0)", "Interactive (1)"], digits=4))

# 4. 繪製簡報用評估圖 (左：混淆矩陣，右：特徵空間散佈圖)
fig, axes = plt.subplots(1, 2, figsize=(11, 4.5), dpi=200)
ConfusionMatrixDisplay(cm, display_labels=["Bulk (0)", "Interactive (1)"]).plot(
    ax=axes[0], cmap="YlGn", colorbar=False
)
axes[0].set_title("Edge Classifier Confusion Matrix")

for lbl, name, color in [(0, "Bulk / Media (0)", "#475569"), (1, "Interactive UDP (1)", "#0F766E")]:
    sub = df[df["label"] == lbl]
    axes[1].scatter(sub["small_ratio"], sub["rx_pps"], alpha=0.65, label=name, c=color, s=24)
axes[1].set_xlabel("Small Packet Ratio (<1200B)")
axes[1].set_ylabel("Rx Packets / sec (PPS)")
axes[1].set_title("Feature Space Separability")
axes[1].legend()
axes[1].grid(alpha=0.3)

plt.tight_layout()
plt.savefig("ml_eval.png", dpi=200)
print("已輸出評估圖表：ml_eval.png")

# 5. 權重折疊並自動寫出 Go 推論檔至 internal/ml/model_gen.go
w_folded = clf.coef_[0] / scaler.scale_
b_folded = clf.intercept_[0] - np.sum(clf.coef_[0] * scaler.mean_ / scaler.scale_)

out_path = os.path.join("internal", "ml", "model_gen.go")
go_code = f"""package ml

import "math"

// Code generated by train_and_export.py (Weight-Folded Logistic Regression). DO NOT EDIT.
func PredictInteractiveProb(s FeatureSample) float64 {{
\tz := ({w_folded[0]:.8f})*s.RxPPS +
\t\t({w_folded[1]:.8f})*s.TxPPS +
\t\t({w_folded[2]:.8f})*s.SmallPktRatio +
\t\t({w_folded[3]:.8f})*s.AvgPktSize +
\t\t({w_folded[4]:.8f})*s.IATVariance +
\t\t({b_folded:.8f})
\treturn 1.0 / (1.0 + math.Exp(-z))
}}
"""

with open(out_path, "w", encoding="utf-8") as f:
    f.write(go_code)
print(f"已自動產出 Go 推論引擎：{out_path}")